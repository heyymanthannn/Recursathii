"""Postgres backend for the RecurSaathi data layer (dual-driver).

PAYRECOVERY_DB starting with postgres:// or postgresql:// routes every
data-layer read and write to PostgreSQL over psycopg 3 (TLS is enforced by
appending sslmode=require when the URL does not set it). Any other value keeps
the stdlib SQLite backend for local development, untouched.

The translation covers exactly the SQLite dialect this codebase uses:
? placeholders, INSERT OR REPLACE / INSERT OR IGNORE, PRAGMA table_info,
strftime(..., 'unixepoch') date grouping, and LIKE search (LIKE becomes
ILIKE so customer search stays case-insensitive like SQLite).

Fail-closed recovery policy: a dropped connection raises cleanly to the
caller (no silent partial writes); every NEW conn() call reconnects with
retry, so the next request or worker tick self-heals.
"""
import os, re, threading, time
from decimal import Decimal

def DB_URL():
    return os.environ.get("PAYRECOVERY_DB", "")

def is_pg():
    return DB_URL().startswith(("postgres://", "postgresql://"))

class Row(dict):
    """sqlite3.Row stand-in: key and positional access, dict() friendly."""
    def __init__(self, mapping, vals=None):
        super().__init__(mapping)
        self._vals = list(vals) if vals is not None else list(mapping.values())
    def __getitem__(self, k):
        if isinstance(k, int):
            return self._vals[k]
        if isinstance(k, str) and k not in self:
            kl = k.lower()
            for key in dict.keys(self):
                if key.lower() == kl:
                    return dict.__getitem__(self, key)
        return dict.__getitem__(self, k)

# ---- SQL translation ----------------------------------------------------
_TABLE_PK = {
    "users": "id", "customers": "id", "invoices": "id", "payments": "id",
    "pay_events": "id", "automations": "id", "etemplates": "id", "outbox": "id",
    "activities": "id", "outbox_history": "id", "audit": "id", "support": "id",
    "plat_pays": "id", "branches": "id", "api_keys": "id", "rules": "id",
    "portal_users": "id", "connect": "owner_id", "merchants": "id",
    "events": "id", "coupons": "code", "messages": "id", "permissions": "id",
    "provider_credentials": "id", "sequences": "id",
    "usage_counters": "owner_id, month, key", "schema_migrations": "version",
}

def _to_pg_fmt(sq):
    return (sq.replace("%Y", "YYYY").replace("%m", "MM").replace("%d", "DD")
              .replace("%H", "HH24").replace("%M", "MI").replace("%S", "SS")
              .replace("%W", "IW"))

def _strftime(m):
    fmt, col = m.group(1), m.group(2)
    return f"to_char(to_timestamp({col}), '{_to_pg_fmt(fmt)}')"

def _pragma(m):
    t = m.group(1)
    return ("SELECT 0 AS cid, column_name AS name, data_type AS type, 0 AS notnull, "
            "NULL AS dflt_value, 0 AS pk FROM information_schema.columns "
            "WHERE table_name = '%s' ORDER BY ordinal_position" % t)

def _walk_values(sql, open_at):
    """Return index just past the ')' closing the VALUES tuple at open_at."""
    depth, i = 1, open_at
    while i < len(sql) and depth:
        i += 1
        if sql[i] == "(": depth += 1
        elif sql[i] == ")": depth -= 1
    return i

def translate(sql):
    if not sql:
        return sql
    s = re.sub(r"strftime\('([^']*)',\s*([A-Za-z_][\w.]*)\s*,\s*'unixepoch'\)", _strftime, sql)
    s = re.sub(r"PRAGMA\s+table_info\((\w+)\)", _pragma, s, flags=re.I)
    m = re.search(r"(?is)INSERT\s+OR\s+REPLACE\s+INTO\s+(\w+)\s*\(([^)]*)\)\s*VALUES\s*\(", s)
    if m:
        table, cols = m.group(1), m.group(2)
        end = _walk_values(s, m.end() - 1)
        values, tail = s[m.end() - 1:end + 1], s[end + 1:]
        pk = _TABLE_PK.get(table, "id")
        sets = ", ".join(f"{c.strip()} = EXCLUDED.{c.strip()}" for c in cols.split(","))
        s = f"INSERT INTO {table} ({cols}) VALUES {values} ON CONFLICT ({pk}) DO UPDATE SET {sets}{tail}"
    else:
        m2 = re.search(r"(?is)INSERT\s+OR\s+IGNORE\s+INTO\s+(\w+)\s*\(([^)]*)\)\s*VALUES\s*\(", s)
        if m2:
            end = _walk_values(s, m2.end() - 1)
            values, tail = s[m2.end() - 1:end + 1], s[end + 1:]
            s = f"INSERT INTO {m2.group(1)} ({m2.group(2)}) VALUES {values} ON CONFLICT DO NOTHING{tail}"
    s = re.sub(r"(?<!I)(?<![A-Za-z_])LIKE(?![A-Za-z_])", "ILIKE", s)
    if re.match(r"(?is)\s*(CREATE|ALTER|DROP)\b", s):
        s = translate_ddl(s)
    s = s.replace("?", "%s")
    s = re.sub(r"%(?!s)", "%%", s)
    return s

_NAME_RE = re.compile(r"(?<![:\w]):([a-zA-Z_][a-zA-Z_0-9]*)")

def translate_named(sql):
    s = _NAME_RE.sub(r"%(\1)s", sql)
    s = re.sub(r"%(?!\()", "%%", s)  # escape bare % not starting a named param
    return s

def translate_ddl(script):
    s = re.sub(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT",
               "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", script, flags=re.I)
    s = re.sub(r"\bREAL\b", "DOUBLE PRECISION", s, flags=re.I)
    s = re.sub(r"\bINTEGER\b", "BIGINT", s, flags=re.I)
    return s

# ---- connection handling -------------------------------------------------
_local = threading.local()

def _connect():
    import psycopg
    url = DB_URL()
    if "sslmode=" not in url:
        url += ("&" if "?" in url else "?") + "sslmode=require"
    last = None
    for attempt in range(4):
        try:
            return psycopg.connect(url, autocommit=False, connect_timeout=10)
        except Exception as e:
            last = e
            time.sleep(0.4 * (attempt + 1))
    raise last

def conn():
    import psycopg
    c = getattr(_local, "conn", None)
    if c is None or c.closed:
        c = _connect()
        _local.conn = c
    return _Conn(c)

def close_all():
    c = getattr(_local, "conn", None)
    if c is not None and not c.closed:
        try: c.close()
        except Exception: pass
    _local.conn = None

def healthy():
    """One cheap round-trip; used by keep-warm paths so the database stays active."""
    try:
        with conn() as c:
            c.execute("SELECT 1")
        return True
    except Exception:
        return False

class _Cursor:
    def __init__(self, cur):
        self._cur = cur
    def _row(self, vals):
        names = [d.name for d in self._cur.description or ()]
        mapping = {}
        for n, v in zip(names, vals):
            if isinstance(v, Decimal):
                v = int(v) if v == v.to_integral_value() else float(v)
            mapping[n] = v
        return Row(mapping, vals)
    def fetchone(self):
        r = self._cur.fetchone()
        return self._row(r) if r is not None else None
    def fetchall(self):
        return [self._row(r) for r in self._cur.fetchall()]
    def __iter__(self):
        for r in self._cur:
            yield self._row(r)
    def __getattr__(self, name):
        return getattr(self._cur, name)

class _Conn:
    def __init__(self, c):
        self._c = c
    def execute(self, sql, args=()):
        cur = self._c.cursor()
        if isinstance(args, dict):
            cur.execute(translate_named(sql), args or None)
        else:
            cur.execute(translate(sql), tuple(args) if args else None)
        return _Cursor(cur)
    def executescript(self, script):
        cur = self._c.cursor()
        for stmt in _split_script(script):
            if stmt.strip():
                cur.execute(translate(stmt))
        cur.close()
    def commit(self): self._c.commit()
    def rollback(self): self._c.rollback()
    def close(self):
        try: self._c.close()
        except Exception: pass
    def __enter__(self): return self
    def __exit__(self, et, ev, tb):
        if et is None:
            self._c.commit()
        else:
            try: self._c.rollback()
            except Exception: pass
        return False

def _split_script(script):
    """Split a DDL script on ';' at top level (no semicolons inside our DDL bodies)."""
    out, buf = [], []
    for ch in script:
        if ch == ";":
            out.append("".join(buf)); buf = []
        else:
            buf.append(ch)
    if buf: out.append("".join(buf))
    return out
