"""Invoice PDF generation (fpdf2) for RecurSaathi."""
import io, os
from fpdf import FPDF
from . import config

def _qr_png(data):
    try:
        import qrcode
        img = qrcode.make(data)
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        return buf.getvalue()
    except Exception:
        return None

def invoice_pdf_bytes(inv, cu, user, pay_url=""):
    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 22)
    pdf.cell(0, 12, "Invoice " + (inv["number"] or ""), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(90, 90, 100)
    pdf.cell(0, 7, user["business"] or user["name"] or "", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 7, "Issued " + (time.strftime("%d %b %Y", time.localtime(inv["created"])) if inv.get("created") else ""), new_x="LMARGIN", new_y="NEXT")
    pdf.ln(6)
    pdf.set_text_color(0, 0, 0)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(0, 8, "Billed to", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    pdf.cell(0, 7, (cu["name"] if cu else "") or "-", new_x="LMARGIN", new_y="NEXT")
    if cu and (cu["email"] or cu["phone"]):
        pdf.cell(0, 7, (cu["email"] or "") + ("  " + cu["phone"] if cu["phone"] else ""), new_x="LMARGIN", new_y="NEXT")
    if inv["description"]:
        pdf.ln(3)
        pdf.set_font("Helvetica", "", 11)
        pdf.multi_cell(0, 7, inv["description"])
    pdf.ln(8)
    pdf.set_draw_color(220, 220, 228)
    pdf.set_fill_color(245, 245, 250)
    pdf.set_font("Helvetica", "B", 12)
    pdf.cell(90, 10, "Amount due", border=1, fill=True)
    pdf.cell(0, 10, "Rs " + f"{(inv['amount'] or 0)/100:,.2f}", border=1, new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    pdf.cell(90, 9, "Due date", border=1)
    pdf.cell(0, 9, inv["due_date"] or "-", border=1, new_x="LMARGIN", new_y="NEXT")
    pdf.cell(90, 9, "Status", border=1)
    pdf.cell(0, 9, (inv["status"] or "pending").capitalize(), border=1, new_x="LMARGIN", new_y="NEXT")
    vpa = user["upi_vpa"]
    if vpa:
        upi = f"upi://pay?pa={vpa}&pn={user['payee_name'] or user['business'] or 'Merchant'}&am={(inv['amount'] or 0)/100:.2f}&cu=INR"
        if inv["number"]:
            upi += "&tn=" + inv["number"].replace(" ", "%20")
        png = _qr_png(upi)
        if png:
            pdf.ln(8)
            pdf.set_font("Helvetica", "B", 11)
            pdf.cell(0, 8, "Scan to pay (UPI / Google Pay)", new_x="LMARGIN", new_y="NEXT")
            pdf.image(io.BytesIO(png), x=pdf.l_margin, w=34)
            pdf.set_font("Helvetica", "", 9)
            pdf.set_text_color(90, 90, 100)
            pdf.cell(0, 6, vpa, new_x="LMARGIN", new_y="NEXT")
    if pay_url:
        pdf.ln(4)
        pdf.set_text_color(0, 0, 0)
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 7, "Payment page: " + pay_url, link=pay_url, new_x="LMARGIN", new_y="NEXT")
    pdf.set_y(-24)
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(130, 130, 140)
    pdf.cell(0, 8, "Generated by RecurSaathi - money goes directly to the business owner's account.", align="C")
    return bytes(pdf.output())

import time  # noqa: E402  (used for the issued date)


def _tbl(pdf, headers, rows, widths):
    pdf.set_font("Helvetica", "B", 10)
    pdf.set_fill_color(245, 245, 250)
    for h, w in zip(headers, widths):
        pdf.cell(w, 8, h, border=1, fill=True)
    pdf.ln()
    pdf.set_font("Helvetica", "", 10)
    for row in rows:
        for cell, w in zip(row, widths):
            pdf.cell(w, 8, str(cell), border=1)
        pdf.ln()

def business_report_pdf_bytes(user, title, sections):
    """Custom business report (Enterprise): each section is
    (heading, [table headers], [rows], [col widths]) or (heading, paragraph)."""
    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 20)
    pdf.cell(0, 12, title, new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(90, 90, 100)
    pdf.cell(0, 7, user["business"] or user["name"] or "", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 7, time.strftime("Generated %d %b %Y, %H:%M"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_text_color(0, 0, 0)
    pdf.ln(4)
    for sec in sections:
        heading, payload = sec[0], sec[1]
        pdf.ln(2)
        pdf.set_font("Helvetica", "B", 13)
        pdf.cell(0, 9, heading, new_x="LMARGIN", new_y="NEXT")
        pdf.set_draw_color(220, 220, 228)
        if payload and isinstance(payload, list) and payload and isinstance(payload[0], (list, tuple)):
            headers, rows, widths = payload
            pdf.set_font("Helvetica", "", 10)
            _tbl(pdf, headers, rows, widths)
        else:
            pdf.set_font("Helvetica", "", 11)
            pdf.multi_cell(0, 7, str(payload or ""))
        pdf.ln(2)
    return bytes(pdf.output())
